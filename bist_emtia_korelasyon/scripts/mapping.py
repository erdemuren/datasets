def build():
    rows = {}
    for key, tickers in GROUPS.items():
        for t in tickers.split():
            sek, et, ger, guv = S[key]
            rows[t] = dict(ticker=t, grup=key, sektor=sek, etkenler=et, gerekce=ger, guven=guv)
    for t, (sek, et, ger, guv) in O.items():
        grp = rows.get(t, {}).get("grup") or ANA_GRUP.get(t, "ozel")
        rows[t] = dict(ticker=t, grup=grp, sektor=sek, etkenler=et, gerekce=ger, guven=guv)
    for v in rows.values():
        v["ana_sektor"] = ana_sektor(v["grup"])
    return rows


def parse_drivers(s):
    out = []
    for tok in [x.strip() for x in s.split(",") if x.strip()]:
        sign = tok[-1] if tok[-1] in "+-?" else "?"
        code = tok[:-1] if tok[-1] in "+-?" else tok
        if code not in FACTORS:
            raise KeyError(f"Bilinmeyen etken kodu: {code}")
        out.append((code, sign))
    return out


